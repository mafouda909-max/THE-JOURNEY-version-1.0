import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const tokenPath = path.join(root, "design", "sila.tokens.json");
const tokens = JSON.parse(fs.readFileSync(tokenPath, "utf8"));

const v = (group, key) => tokens[group][key].value;

const css = `/* AUTO-GENERATED by scripts/generate-design-tokens.mjs — do not edit manually. */
:root {
  --sila-ink: ${v("color","ink")};
  --sila-horizon: ${v("color","horizon")};
  --sila-signal: ${v("color","signal")};
  --sila-sky: ${v("color","sky")};
  --sila-air: ${v("color","air")};
  --sila-paper: ${v("color","paper")};
  --sila-cloud: ${v("color","cloud")};
  --sila-dark: ${v("color","dark")};
  --sila-text: ${v("color","text")};
  --sila-muted: ${v("color","muted")};
  --sila-outline: ${v("color","outline")};
  --sila-verified: ${v("color","verified")};
  --sila-verified-bg: ${v("color","verifiedBg")};
  --sila-warning: ${v("color","warning")};
  --sila-warning-bg: ${v("color","warningBg")};
  --sila-error: ${v("color","error")};
  --sila-error-bg: ${v("color","errorBg")};
  --sila-radius-window: ${v("radius","window")}px;
  --sila-radius-hero: ${v("radius","hero")}px;
  --sila-shadow-soft: ${v("shadow","soft")};
  --sila-shadow-raised: ${v("shadow","raised")};
  --sila-motion-fast: ${v("motion","fast")}ms;
  --sila-motion-base: ${v("motion","base")}ms;
  --sila-motion-slow: ${v("motion","slow")}ms;
  --sila-motion-ease: ${v("motion","ease")};
  --sila-layout-max: ${v("layout","max")}px;
  --sila-reading-max: ${v("layout","reading")}px;
}
`;

const mobile = `/* AUTO-GENERATED by scripts/generate-design-tokens.mjs — do not edit manually. */
export const generatedBrandTokens = ${JSON.stringify({
  colors:Object.fromEntries(Object.entries(JSON.parse(tokens ? JSON.stringify(tokens.color) : "{}")).map(([k,o])=>[k,o.value])),
  spacing:Object.fromEntries(Object.entries(JSON.parse(tokens ? JSON.stringify(tokens.space) : "{}")).map(([k,o])=>[k,Number(o.value)])),
  radius:Object.fromEntries(Object.entries(JSON.parse(tokens ? JSON.stringify(tokens.radius) : "{}")).map(([k,o])=>[k,Number(o.value)])),
  motion:Object.fromEntries(Object.entries(JSON.parse(tokens ? JSON.stringify(tokens.motion) : "{}")).map(([k,o])=>[k,o.value])),
  layout:Object.fromEntries(Object.entries(JSON.parse(tokens ? JSON.stringify(tokens.layout) : "{}")).map(([k,o])=>[k,Number(o.value)])),
}, null, 2)} as const;
`;

fs.mkdirSync(path.join(root, "src", "styles"), { recursive: true });
fs.writeFileSync(path.join(root, "src", "styles", "sila-generated.css"), css);
fs.writeFileSync(path.join(root, "mobile", "src", "generated-brand-tokens.ts"), mobile);
console.log("SILA design tokens synchronized.");
